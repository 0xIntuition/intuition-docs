#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const { versions } = require('../docs-versions.config');
const { walkFiles } = require('./lib/docs-tree');
const { transformContent } = require('./codemods/v1-prefix-links');
const ROOT = path.resolve(__dirname, '..');

// FR-14: add only fixes demonstrated by a throwing Docusaurus build. Every
// record must identify its file, oldTarget, newTarget, occurrences and evidence.
const LINK_FIXES = [];

function applyLinkFixes(content, relativePath, fixes = LINK_FIXES) {
  let expected = content;
  for (const fix of fixes.filter((entry) => entry.file === relativePath)) {
    if (!fix.evidence || !fix.oldTarget || !fix.newTarget || !Number.isInteger(fix.occurrences) || fix.occurrences < 1) {
      throw new Error(`Incomplete V1 link-fix record: ${relativePath}`);
    }
    const count = expected.split(fix.oldTarget).length - 1;
    if (count !== fix.occurrences) throw new Error(`V1 link-fix occurrence mismatch: ${relativePath}: expected ${fix.occurrences}, got ${count}`);
    expected = expected.split(fix.oldTarget).join(fix.newTarget);
  }
  return expected;
}

function compareSnapshot(baseFiles, snapshotFiles, fixes = LINK_FIXES) {
  const failures = [];
  for (const [relativePath, original] of baseFiles) {
    const actual = snapshotFiles.get(relativePath);
    if (actual === undefined) { failures.push(`Missing snapshot file: ${relativePath}`); continue; }
    const expected = applyLinkFixes(transformContent(original), relativePath, fixes);
    if (actual !== expected) failures.push(`Unexpected snapshot content change: ${relativePath}`);
  }
  for (const relativePath of snapshotFiles.keys()) {
    if (!baseFiles.has(relativePath)) failures.push(`Unexpected snapshot file: ${relativePath}`);
  }
  for (const fix of fixes) {
    if (!baseFiles.has(fix.file)) failures.push(`Link-fix record references absent base file: ${fix.file}`);
  }
  return failures;
}

function validateSnapshot(root = ROOT) {
  const base = versions.v1.sourceCommit;
  const sourceDir = versions.current.docsDir;
  const files = execFileSync('git', ['ls-tree', '-r', '--name-only', '-z', base, '--', sourceDir], { cwd: root, encoding: 'utf8' }).split('\0').filter(Boolean);
  if (!files.length) throw new Error(`No snapshot sources at ${base}:${sourceDir}`);
  const baseFiles = new Map(files.map((file) => [file.slice(sourceDir.length + 1), execFileSync('git', ['show', `${base}:${file}`], { cwd: root, encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 })]));
  const snapshotDir = path.join(root, versions.v1.docsDir);
  const snapshotFiles = new Map(walkFiles(snapshotDir).map((file) => [path.relative(snapshotDir, file).replace(/\\/g, '/'), fs.readFileSync(file, 'utf8')]));
  const failures = compareSnapshot(baseFiles, snapshotFiles);
  failures.push(...validateVersionMetadata(root));
  return { failures, files: files.length, base, linkFixes: LINK_FIXES };
}

function validateVersionMetadata(root = ROOT) {
  const failures = [];
  const base = versions.v1.sourceCommit;
  const versionNames = JSON.parse(fs.readFileSync(path.join(root, '_data_versions.json'), 'utf8'));
  if (JSON.stringify(versionNames) !== JSON.stringify(['v1'])) failures.push('Version inventory must contain only v1.');
  // Native docs:version serializes the original sidebar without resolving its
  // autogenerated items. Preserve that exact JSON representation as well.
  const baseSidebarSource = execFileSync('git', ['show', `${base}:sidebars.js`], { cwd: root, encoding: 'utf8' });
  const vm = require('node:vm');
  const context = { module: { exports: {} } };
  vm.runInNewContext(baseSidebarSource, context, { timeout: 1000 });
  const expectedSidebar = `${JSON.stringify(context.module.exports, null, 2)}\n`;
  if (fs.readFileSync(path.join(root, '_data_versioned_sidebars/version-v1-sidebars.json'), 'utf8') !== expectedSidebar) failures.push('Unexpected snapshot sidebar change.');
  return failures;
}

if (require.main === module) {
  try {
    const result = validateSnapshot();
    if (result.failures.length) throw new Error(result.failures.join('\n'));
    console.log(`V1 snapshot matches ${result.files} transformed source files at ${result.base}; ${result.linkFixes.length} recorded link fixes.`);
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}

module.exports = { LINK_FIXES, applyLinkFixes, compareSnapshot, validateSnapshot, validateVersionMetadata };
