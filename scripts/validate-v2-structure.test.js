function doc(
  file = 'index.md',
  changes = {},
  body = 'Version-neutral documentation.',
) {
  const fields = {
    title: 'Docs',
    sidebar_label: 'Docs',
    description: 'A useful description.',
    kind: 'concept',
    reader: '["app"]',
    packages: '[]',
    ...changes,
  };
  return docMetadata(
    file,
    `---\n${Object.entries(fields)
      .map(([key, value]) => `${key}: ${value}`)
      .join('\n')}\n---\n${body}\n`,
    versions.current,
  );
}
