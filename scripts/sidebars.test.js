const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const test = require('node:test');
const matter = require('gray-matter');
const { tutorialSidebar } = require('../sidebars');

const docsRoot = path.resolve(__dirname, '../docs/_data');
function documents(directory = docsRoot) {
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    if (entry.name.startsWith('_') || entry.name.startsWith('.')) return [];
    const file = path.join(directory, entry.name);
    if (entry.isDirectory()) return documents(file);
    if (!/\.mdx?$/.test(entry.name)) return [];
    const { data } = matter(fs.readFileSync(file, 'utf8'));
    const relative = path.relative(docsRoot, file).split(path.sep).join('/');
    const id = path.posix.join(
      path.posix.dirname(relative),
      data.id || entry.name.replace(/\.mdx?$/, ''),
    );
    return [{ id, relative }];
  });
}

test('curated navigation includes every document exactly once', () => {
  const docs = documents();
  const ids = [];
  function collect(items) {
    for (const item of items) {
      if (typeof item === 'string') ids.push(item);
      else if (item.type === 'doc') ids.push(item.id);
      else if (item.type === 'autogenerated') {
        ids.push(
          ...docs
            .filter((doc) => doc.relative.startsWith(`${item.dirName}/`))
            .map((doc) => doc.id),
        );
      } else if (item.type === 'category') {
        if (item.link?.type === 'doc') ids.push(item.link.id);
        collect(item.items);
      }
    }
  }
  collect(tutorialSidebar);
  assert.equal(ids.length, new Set(ids).size, 'Duplicate navigation entries');
  assert.deepEqual([...ids].sort(), docs.map((doc) => doc.id).sort());
});
